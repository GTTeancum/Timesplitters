"""Writes the Xbox build's function table from project/generated/register_functions.cpp.

The generated table has a slot for every 4-byte guest address in the code
region (about 245,000 slots, 1 MB) filled in by a constructor. The Xbox has
64 MB, so it gets two sorted arrays of the used entries instead, statically
initialised; ps2_runtime.cpp looks addresses up by binary search there.
direct_calls.py reads the address array back out of the output (a target's
slot is its index there) to resolve the generated files' constant calls.

usage: compact_function_table.py <register_functions.cpp> <output.cpp>

The second form writes the natives' call-slot header (B-CODEGEN, M3.2,
src/xbox/PUSH-BC-PLAN.md section 5.2; src/xbox/mk/b_codegen.mk runs it):

usage: compact_function_table.py --slots <register_functions_xbox.cpp> <output.h> <source.cpp>...

It collects every constant guestCall / lightCall target in the given
native sources, resolves each to its slot in the compact table (the one
the first form wrote, so the two cannot disagree) and writes
build/xbox/gen/ps2_function_slots_xbox.h: `ps2SlotOf(target)`, a constexpr
switch over those targets (a switch on a constant folds to the slot at
every inlined call site; an address it does not list gives
PS2X_NO_FUNCTION_SLOT and the caller falls back to dispatchGuestBranch),
and the target list for the boot check (ps2_native_call_xbox.h,
TS_CALL_SLOT_CHECK). A target the table has no entry for is left out and
reported: the old path serves it, as before.
"""
import os
import re
import sys

import direct_calls

NO_SLOT = 0xFFFFFFFF
# guestCall(G_PASS, 0xTu, ...) / lightCall(rdram, ctx, runtime, 0xTu, ...):
# the first hex constant after the helper's name is the target.
CALL_TARGET = re.compile(r"\b(?:guestCall|lightCall)\((?:G_PASS|rdram, ctx, runtime), (0x[0-9A-Fa-f]+)u")


def write_table(source, output):
    text = open(source).read()
    base = int(re.search(r"g_ps2RecompiledFunctionTableBase = (0x[0-9a-fA-F]+)u", text).group(1), 16)
    end = int(re.search(r"g_ps2RecompiledFunctionTableEnd = (0x[0-9a-fA-F]+)u", text).group(1), 16)
    entries = {}
    for slot, name in re.findall(r"g_ps2RecompiledFunctionTable\[(\d+)\] = (\w+);", text):
        entries[base + int(slot) * 4] = name
    includes = [line for line in text.splitlines() if line.startswith("#include")]
    addresses = sorted(entries)

    lines = ["// Generated by src/xbox/tools/compact_function_table.py; do not edit."]
    lines += includes
    lines.append("")
    lines.append("extern const uint32_t g_ps2RecompiledFunctionTableBase = 0x%xu;" % base)
    lines.append("extern const uint32_t g_ps2RecompiledFunctionTableEnd = 0x%xu;" % end)
    lines.append("extern const uint32_t g_ps2RecompiledFunctionTableSlotCount = %du;" % len(addresses))
    lines.append("extern const uint32_t g_ps2RecompiledFunctionAddresses[%d] = {" % len(addresses))
    lines += ["    0x%xu," % a for a in addresses]
    lines.append("};")
    lines.append("PS2Runtime::RecompiledFunction g_ps2RecompiledFunctionTable[%d] = {" % len(addresses))
    lines += ["    %s," % entries[a] for a in addresses]
    lines.append("};")
    open(output, "w").write("\n".join(lines) + "\n")


def call_targets(sources):
    """The constant call targets of the native sources, sorted."""
    targets = set()
    for path in sources:
        for hex_target in CALL_TARGET.findall(open(path).read()):
            targets.add(int(hex_target, 16))
    return sorted(targets)


def slots_header_text(slots, targets, sources):
    """The text of ps2_function_slots_xbox.h for these targets."""
    resolved = [(t, slots[t]) for t in targets if t in slots]
    missing = [t for t in targets if t not in slots]
    lines = [
        "// Generated by src/xbox/tools/compact_function_table.py --slots; do not edit.",
        "// The natives' constant guest-call targets (%s) resolved to their slots" % ", ".join(os.path.basename(s) for s in sources),
        "// in the compact function table (register_functions_xbox.cpp): see",
        "// ps2_native_call_xbox.h (PS2X_GUEST_CALL).",
        "#ifndef PS2_FUNCTION_SLOTS_XBOX_H",
        "#define PS2_FUNCTION_SLOTS_XBOX_H",
        "#include <cstdint>",
        "",
        "#define PS2X_NO_FUNCTION_SLOT 0xFFFFFFFFu",
        "#define PS2X_FUNCTION_SLOT_COUNT %du" % len(slots),
        "#define PS2X_NATIVE_CALL_TARGETS %du" % len(resolved),
        "#define PS2X_NATIVE_CALL_TARGETS_UNRESOLVED %du" % len(missing),
        "",
        "// The slot of a listed target; PS2X_NO_FUNCTION_SLOT for any other",
        "// address. A switch on a constant folds at every inlined call site, so",
        "// a call with a literal target costs no lookup at all; a non-constant",
        "// target is a small binary search, still exact.",
        "constexpr uint32_t ps2SlotOf(uint32_t target)",
        "{",
        "    switch (target)",
        "    {",
    ]
    for target, slot in resolved:
        lines.append("    case 0x%xu: return %du;" % (target, slot))
    lines += [
        "    default: return PS2X_NO_FUNCTION_SLOT;",
        "    }",
        "}",
        "",
        "// Every listed target with its slot, for the boot check",
        "// (TS_CALL_SLOT_CHECK compares each against the runtime's table).",
        "struct Ps2FunctionSlotEntry",
        "{",
        "    uint32_t address;",
        "    uint32_t slot;",
        "};",
        "constexpr Ps2FunctionSlotEntry kPs2NativeCallTargets[%d] = {" % max(1, len(resolved)),
    ]
    for target, slot in resolved:
        lines.append("    {0x%xu, %du}," % (target, slot))
    if not resolved:
        lines.append("    {0u, PS2X_NO_FUNCTION_SLOT},")
    lines += ["};", ""]
    if missing:
        lines.append("// Targets without a table entry (served by dispatchGuestBranch, which")
        lines.append("// reports them): " + ", ".join("0x%x" % t for t in missing))
        lines.append("")
    lines.append("#endif // PS2_FUNCTION_SLOTS_XBOX_H")
    return "\n".join(lines) + "\n", resolved, missing


def write_slots_header(table_cpp, output, sources):
    slots = direct_calls.read_slots(table_cpp)
    targets = call_targets(sources)
    text, resolved, missing = slots_header_text(slots, targets, sources)
    # Only rewrite when the text changes: the natives depend on this header.
    if not (os.path.exists(output) and open(output).read() == text):
        open(output, "w").write(text)
    if missing:
        print("compact_function_table: %d call targets without a table entry: %s"
              % (len(missing), " ".join("0x%x" % t for t in missing)))
    return len(resolved), len(missing)


if __name__ == "__main__":
    if len(sys.argv) >= 4 and sys.argv[1] == "--slots":
        write_slots_header(sys.argv[2], sys.argv[3], sys.argv[4:])
    elif len(sys.argv) == 3:
        write_table(sys.argv[1], sys.argv[2])
    else:
        raise SystemExit(__doc__)
